const assert = require('node:assert/strict');
const {accessDate, render, rtf} = require('../citations-format.js');
assert.equal(accessDate('2026-02-30'), '');
assert.equal(accessDate('2024-02-29'), 'February 29, 2024');
assert.equal(accessDate('2026-13-01'), '');
const source = {html:'Author. <em>Title</em>.',plain:'Author. Title.',url:'https://example.org/?a=1&b=2',needsAccessDate:true};
assert.equal(render(source, '').ready, false);
assert.equal(render(source, '2026-02-30').ready, false);
const ready = render(source, '2026-10-30');
assert.equal(ready.ready, true);
assert.match(ready.plain, /Accessed October 30, 2026\./);
assert.match(ready.html, /a=1&amp;b=2/);
assert.doesNotMatch(ready.plain, /<em>|&amp;/);
assert.equal(render({...source, needsAccessDate:false}, '').ready, true);
const rich = rtf('“<em>Weather &amp; Words</em>.” Ж {test} \\');
assert.match(rich, /\\li720\\fi-720/);
assert.ok(rich.includes('{\\i Weather & Words}'));
assert.ok(rich.includes('\\u8220?'));
assert.ok(rich.includes('\\u1046?'));
assert.ok(rich.includes('\\{test\\}'));
assert.ok(rich.includes('\\\\'));
assert.doesNotMatch(rich, /<em>|&amp;/);
console.log('Citation export checks passed: dates, readiness, plain text, italics, Unicode, and RTF escaping.');
